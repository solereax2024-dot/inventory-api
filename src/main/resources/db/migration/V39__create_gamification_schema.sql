-- Customer Badges (earned badges for each customer)
CREATE TABLE customer_badges (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    customer_id BIGINT NOT NULL REFERENCES customer_profiles(id) ON DELETE CASCADE,
    badge_id BIGINT NOT NULL REFERENCES badge_definitions(id),
    earned_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT uq_customer_badge UNIQUE (customer_id, badge_id)
);

CREATE INDEX idx_customer_badges_customer ON customer_badges(customer_id);

-- Daily Activities (for daily spin wheel and activities)
CREATE TABLE daily_activities (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    customer_id BIGINT NOT NULL REFERENCES customer_profiles(id) ON DELETE CASCADE,
    activity_type VARCHAR(50) NOT NULL, -- SPIN_WHEEL, PURCHASE, REVIEW, REFERRAL
    points_earned INT NOT NULL,
    activity_date DATE NOT NULL,
    completed_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE INDEX idx_daily_activities_customer ON daily_activities(customer_id);
CREATE INDEX idx_daily_activities_date ON daily_activities(activity_date);

-- Points Redemptions (track when customers redeem points)
CREATE TABLE points_redemptions (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    customer_id BIGINT NOT NULL REFERENCES customer_profiles(id) ON DELETE CASCADE,
    points_amount INT NOT NULL,
    redemption_type VARCHAR(50) NOT NULL, -- DISCOUNT_CODE, FREE_SHIPPING
    reference_id VARCHAR(120),
    redeemed_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE INDEX idx_points_redemptions_customer ON points_redemptions(customer_id);

